#!/bin/bash
# gen-page-vectors.sh — 用 WebKit 实际渲染样稿 research/pc-v3（snap 工具，PORT-PLAN 附录 B），跑 probe-overview.js / probe-device.js / probe-texts.js，
# 把每个场景量到的版面（根尺寸、网格、卡片容器尺寸与按容器查询得出的取舍）和报警 / 事件文字写成 PageMockVectors.cs。
# Core 的 Layout/OverviewLayout、Layout/DeviceLayout、Alarms/AlarmBook、Events/EventBook 的测试拿它当参照（OverviewLayoutTests / DeviceLayoutTests /
# AlarmBookTests / EventBookTests）：期望值全部来自样稿自己的 CSS / JS 在 WebKit 里的结果，不手写。
# 用法（必须在 bash 下；输出目录放在 scratch）：
#   bash gen-page-vectors.sh <snap 可执行文件> <research/pc-v3 目录> <输出目录> > PageMockVectors.cs
# 场景 = 路由 + 地址参数（与样稿 README「常用查询参数」相同）× 1920×1080 / 1600×900 / 1366×768。
set -euo pipefail
SNAP="$1"; MOCK="$2"; OUT="$3"
HERE="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$OUT"
: > "$OUT/index.tsv"
probe() { # kind probe w h route name [pre]
  local js
  js="${7:-}
$(cat "$HERE/$2")"
  "$SNAP" "$MOCK/index.html" "$OUT/$6.png" "$3" "$4" "$5" 1300 "$js" 2>&1 | grep -E 'PROBE' | sed 's/^\[page\] warn: PROBE //' > "$OUT/$6.json"
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$1" "$6" "$3" "$4" "$5" "${7:-}" >> "$OUT/index.tsv"
}
sizes="1920x1080 1600x900 1366x768"
ov=("" "devs=4" "stress=1" "stress=2" "devs=4&stress=1" "devs=4&stress=2" "explorer=0" "tl=0" "devs=PR8,PR4,PR16&offline=none"
    "devs=PR8,PR4,PR16&offline=none&stress=1" "devs=1" "estop=1,2,3&offline=3" "estop=1,2,3&offline=3&stress=2" "explorer=0&tl=0&stress=1" "devs=PR16,PR4&stress=2")
i=0
for p in "${ov[@]}"; do
  for sz in $sizes; do
    w=${sz%x*}; h=${sz#*x}; q="bare=1&freeze=1"; [ -n "$p" ] && q="$q&$p"
    probe overview probe-overview.js "$w" "$h" "/overview?$q" "ov-$i-$w"
  done
  i=$((i+1))
done
dv=("" "stress=1" "stress=2" "explorer=0" "tl=0" "estop=1,2,3&offline=3" "explorer=0&tl=0" "explorer=0&tl=0&stress=1" "alarm=1:1,2:1")
i=0
for p in "${dv[@]}"; do
  for k in 1 2 3; do
    for sz in $sizes; do
      w=${sz%x*}; h=${sz#*x}; q="bare=1&freeze=1"; [ -n "$p" ] && q="$q&$p"
      probe device probe-device.js "$w" "$h" "/device/$k?$q" "dv-$i-$k-$w"
    done
  done
  i=$((i+1))
done
i=0
for p in "devs=4" "devs=4&stress=1" "devs=4&estop=4" "devs=4&tl=0&explorer=0" \
         "devs=PR8,PR4,PR16&offline=none" "devs=PR8,PR4,PR16&offline=none&stress=1" "devs=PR8,PR4,PR16&offline=none&tl=0" "devs=PR8,PR4,PR16&offline=none&tl=0&explorer=0&stress=2"; do
  k=4; case "$p" in devs=PR8*) k=1;; esac
  for sz in $sizes; do
    w=${sz%x*}; h=${sz#*x}
    probe device probe-device.js "$w" "$h" "/device/$k?bare=1&freeze=1&$p" "dx-$i-$k-$w"
  done
  i=$((i+1))
done
# 报警 / 事件文字（总览 1366：报警条出现；设备页 1920：三列；1600：页签）
i=0
for p in "" "devs=4" "stress=1" "stress=2" "estop=1,2,3&offline=3" "alarm=1:1,2:1" "devs=4&alarm=4:1" "estop=2&alarm=2:1" "devs=PR8,PR4,PR16&offline=none" "alarm=3:0" "devs=4&stress=2&estop=3"; do
  q="bare=1&freeze=1"; [ -n "$p" ] && q="$q&$p"
  probe texts probe-texts.js 1366 768 "/overview?$q" "to-$i"
  i=$((i+1))
done
probe texts probe-texts.js 1366 768 "/overview?bare=1&freeze=1&stress=1" "to-ack" "PR.sim.act(PR.sim.dev(3), 'alarmAck', { id: PR.sim.dev(3).alarms[0].id });"
i=0
for p in "" "stress=1" "stress=2" "estop=1,2,3&offline=3" "alarm=1:1,2:1" "alarm=3:0" "estop=2"; do
  q="bare=1&freeze=1"; [ -n "$p" ] && q="$q&$p"
  for k in 1 2 3; do probe texts probe-texts.js 1920 1080 "/device/$k?$q" "td-$i-$k"; done
  i=$((i+1))
done
i=0
for p in "devs=4" "devs=4&stress=1" "devs=4&estop=4"; do
  probe texts probe-texts.js 1920 1080 "/device/4?bare=1&freeze=1&$p" "td4-$i"
  i=$((i+1))
done
i=0
for p in "" "stress=1" "alarm=1:1" "estop=1"; do
  q="bare=1&freeze=1"; [ -n "$p" ] && q="$q&$p"
  for k in 1 2 3; do probe texts probe-texts.js 1600 900 "/device/$k?$q" "tt-$i-$k"; done
  i=$((i+1))
done
probe texts probe-texts.js 1920 1080 "/device/3?bare=1&freeze=1" "td-ack-3" "PR.sim.act(PR.sim.dev(3), 'alarmAck', { id: PR.sim.dev(3).alarms[0].id });"
probe texts probe-texts.js 1920 1080 "/device/1?bare=1&freeze=1&alarm=1:1" "td-ack-1" "PR.sim.act(PR.sim.dev(1), 'alarmAck', { id: PR.sim.dev(1).alarms[0].id });"

python3 -I - "$OUT" <<'PY'
import json, sys, os
out = sys.argv[1]
rows = [l.rstrip('\n').split('\t') for l in open(os.path.join(out, 'index.tsv'), encoding='utf-8')]
data = {'source': 'research/pc-v3（WebKit，snap）· probe-overview.js / probe-device.js / probe-texts.js', 'overview': [], 'device': [], 'texts': []}
for kind, name, w, h, route, pre in rows:
    txt = open(os.path.join(out, name + '.json'), encoding='utf-8').read().strip()
    if not txt: raise SystemExit('no probe output for ' + name)
    data[kind].append({'name': name, 'w': int(w), 'h': int(h), 'route': route, 'pre': pre, 'probe': json.loads(txt.splitlines()[0])})
raw = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
if '"""""' in raw: raise SystemExit('raw string delimiter clash')
print('// <auto-generated>')
print('// 由 MockVectors/gen-page-vectors.sh 用样稿 research/pc-v3 在 WebKit（snap）里实际渲染、跑 probe-*.js 量出来，不要手改；')
print('// 样稿改了就重新生成（命令见脚本开头）。overview / device：版面（根尺寸、网格、卡片容器尺寸、按容器查询得出的取舍）；texts：报警与事件文字。')
print('// </auto-generated>')
print('namespace ParallelReactor.Control.Tests;')
print('')
print('internal static class PageMockVectors')
print('{')
print('    public const string Json = """""')
print(raw)
print('""""";')
print('}')
PY
